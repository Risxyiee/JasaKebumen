/**
 * OpenNext (@opennextjs/cloudflare) build fixes for Prisma 6 + node-postgres.
 *
 * Fix 1 — pg-cloudflare exports (tracing vs bundling condition mismatch):
 *   OpenNext traces files with Node.js conditions but bundles with the
 *   "workerd" condition. pg-cloudflare's exports map resolves "." to
 *   "./dist/empty.js" (default) vs "./dist/index.js" (workerd), so the tracer
 *   copies only dist/empty.js and esbuild fails with:
 *     ERROR: Could not resolve "pg-cloudflare"
 *   → Flatten the exports map so every condition resolves to the real
 *     implementation (./dist/index.js). Harmless on Node.js.
 *
 * Fix 2 — missing @prisma/client/wasm.mjs shim:
 *   @prisma/client's exports map points the "import" condition of "./wasm" to
 *   ./wasm.mjs, which Prisma does not publish (only ./wasm.js exists).
 *   ESM resolvers (e.g. Turbopack) therefore fail with "Module not found".
 *   → Write a tiny ESM shim that re-exports the CJS wasm entry.
 *
 * Both fixes are idempotent and fail safe (never break `bun install`).
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

function readJSON(p) {
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

function fixPgCloudflare() {
  const pkgPath = path.join(ROOT, "node_modules", "pg-cloudflare", "package.json");
  if (!fs.existsSync(pkgPath)) {
    console.log("[prisma-opennext-fix] pg-cloudflare not found — skipping");
    return;
  }
  const pkg = readJSON(pkgPath);
  const dot = pkg.exports && pkg.exports["."];
  if (dot && dot.workerd) {
    pkg.exports["."] = { default: "./dist/index.js" };
    fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
    console.log("[prisma-opennext-fix] pg-cloudflare exports flattened to ./dist/index.js");
  } else {
    console.log("[prisma-opennext-fix] pg-cloudflare exports already flat");
  }
}

function fixPrismaWasmMjs() {
  const clientDir = path.join(ROOT, "node_modules", "@prisma", "client");
  const wasmMjs = path.join(clientDir, "wasm.mjs");
  if (!fs.existsSync(path.join(clientDir, "wasm.js"))) {
    console.log("[prisma-opennext-fix] @prisma/client not found — skipping");
    return;
  }
  if (fs.existsSync(wasmMjs)) {
    console.log("[prisma-opennext-fix] @prisma/client/wasm.mjs already exists");
    return;
  }
  const shim =
    `// Generated by scripts/fix-prisma-opennext.cjs — ESM shim for the missing wasm.mjs\n` +
    `import client from "./wasm.js";\n` +
    `export default client;\n` +
    `export const PrismaClient = client.PrismaClient;\n`;
  fs.writeFileSync(wasmMjs, shim);
  console.log("[prisma-opennext-fix] created @prisma/client/wasm.mjs shim");
}

try {
  fixPgCloudflare();
  fixPrismaWasmMjs();
} catch (err) {
  console.warn("[prisma-opennext-fix] WARN:", err && err.message);
}
